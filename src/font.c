#define GLYPH_COUNT ((int)(sizeof(GLYPHS) / sizeof(GLYPHS[0])))


static const Glyph *find_glyph(char ch)
{
    if (ch >= 'a' && ch <= 'z') {
        ch = (char)(ch - 'a' + 'A');
    }

    for (int i = 0; i < GLYPH_COUNT; i++) {
        if (GLYPHS[i].ch == ch) {
            return &GLYPHS[i];
        }
    }

    return NULL;   /* space or unsupported character */
}


void font_draw_text(const char *text, int x, int y, int pixel)
{
    if (text == NULL || pixel <= 0) {
        return;
    }

    for (int i = 0; text[i] != '\0'; i++) {
        const Glyph *glyph = find_glyph(text[i]);
        int left = x + i * CHAR_ADVANCE * pixel;

        if (glyph == NULL) {
            continue;
        }

        for (int row = 0; row < FONT_GLYPH_HEIGHT; row++) {
            for (int col = 0; col < FONT_GLYPH_WIDTH; col++) {
                if (glyph->rows[row][col] == '#') {
                    gfx_fillrectangle(left + col * pixel,
                                      y + row * pixel,
                                      pixel, pixel);
                }
            }
        }
    }
}


int font_text_width(const char *text, int pixel)
{
    if (text == NULL || text[0] == '\0') {
        return 0;
    }

    int length = (int)strlen(text);

    /* No trailing gap after the last character. */
    return (length * CHAR_ADVANCE - 1) * pixel;
}


int font_text_height(int pixel)
{
    return FONT_GLYPH_HEIGHT * pixel;
}


int font_glyph_pixel(char ch, int col, int row)
{
    const Glyph *glyph = find_glyph(ch);

    if (glyph == NULL ||
        col < 0 || col >= FONT_GLYPH_WIDTH ||
        row < 0 || row >= FONT_GLYPH_HEIGHT) {
        return 0;
    }

    return glyph->rows[row][col] == '#';
}
